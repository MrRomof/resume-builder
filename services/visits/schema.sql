CREATE TABLE IF NOT EXISTS visitors (id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY CHECK(id=1), views INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO totals(id, views) VALUES(1, 0);
CREATE TRIGGER IF NOT EXISTS count_event AFTER INSERT ON events BEGIN
  UPDATE totals SET views = views + 1 WHERE id = 1;
END;
